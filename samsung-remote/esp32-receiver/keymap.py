"""Map Samsung remote key codes to button names.

Press a button on the remote, type its name, repeat. Every answer is saved
right away to keymap.json and main/samsung_keymap.h (the firmware's name
table; rebuild + flash to use it). Ctrl+C saves and quits.

Run through ./keymap.sh. Close monitor.sh first: the serial port is exclusive.
"""

import json
import os
import re
import signal
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
JSON_PATH = os.path.join(HERE, "keymap.json")
HEADER_PATH = os.path.join(HERE, "main", "samsung_keymap.h")

SKEY_UP = re.compile(
    r"SKEY UP\s+0x([0-9a-f]{2}) (\S+) held=(\d+)ms reports=(\d+) checksum=(\w+)")


def load():
    if os.path.exists(JSON_PATH):
        with open(JSON_PATH) as f:
            return {int(k, 16): v for k, v in json.load(f).items()}
    return {0xd2: "Power"}


def save(keymap):
    with open(JSON_PATH, "w") as f:
        json.dump({f"0x{k:02x}": v for k, v in sorted(keymap.items())}, f, indent=2)
        f.write("\n")
    rows = "".join(f'    {{0x{k:02x}, "{v.replace(chr(92), "").replace(chr(34), "")}"}},\n'
                   for k, v in sorted(keymap.items()))
    with open(HEADER_PATH, "w") as f:
        f.write("/* Samsung key code -> button name. Regenerated by ../keymap.py */\n"
                "#pragma once\n\n#include <stdint.h>\n\n"
                "static const struct {\n    uint8_t code;\n    const char *name;\n"
                "} SAMSUNG_KEYMAP[] = {\n" + rows + "};\n")


class SerialLines:
    def __init__(self, port):
        import serial
        try:
            self.s = serial.Serial(port, 115200, timeout=0.2, exclusive=True)
        except serial.SerialException as e:
            sys.exit(f"Cannot open {port}: {e}\nClose monitor.sh (or anything else using the port) first.")
        self.buf = b""

    def next_line(self):
        while b"\n" not in self.buf:
            self.buf += self.s.read(4096)
        line, self.buf = self.buf.split(b"\n", 1)
        return line.decode(errors="replace")

    def flush(self):
        """Drop anything pressed while the user was typing."""
        self.s.reset_input_buffer()
        self.buf = b""


class ReplayLines:
    """--replay LOG: feed a saved log instead of the serial port (for testing)."""
    def __init__(self, path):
        self.lines = open(path, errors="replace").read().splitlines()

    def next_line(self):
        if not self.lines:
            raise EOFError
        return self.lines.pop(0)

    def flush(self):
        pass


def main():
    # Ctrl+C must work even if the shell started us with SIGINT ignored
    signal.signal(signal.SIGINT, signal.default_int_handler)

    if len(sys.argv) >= 3 and sys.argv[1] == "--replay":
        src = ReplayLines(sys.argv[2])
    else:
        src = SerialLines(sys.argv[1])

    keymap = load()
    print(f"{len(keymap)} buttons known. Press a button on the remote, then type its name.")
    print("Enter keeps the current name (or skips). Ctrl+C saves and quits.\n")
    try:
        while True:
            print("Waiting for a button...", flush=True)
            while True:
                m = SKEY_UP.search(src.next_line())
                if m:
                    break
            code = int(m.group(1), 16)
            current = keymap.get(code)
            print(f"  got 0x{code:02x} (held {m.group(3)} ms, {m.group(4)} reports, "
                  f"checksum {m.group(5)})" + (f", currently \"{current}\"" if current else ""))
            name = input("  name: ").strip()
            if name:
                keymap[code] = name
                save(keymap)
                print(f"  saved 0x{code:02x} = {name}\n")
            else:
                print("  unchanged\n")
            src.flush()
    except (KeyboardInterrupt, EOFError):
        pass

    save(keymap)
    print("\n\nKey map:")
    for k, v in sorted(keymap.items()):
        print(f"  0x{k:02x}  {v}")
    print(f"\nSaved {JSON_PATH} and {HEADER_PATH}. Rebuild + flash to use the names.")


if __name__ == "__main__":
    main()
